/**
 * Regenerates every piece of committed test evidence in one go:
 *
 *   npm run results
 *
 * Runs each Cucumber profile, the self-healing POC and the SQL checks, saves each console log to
 * reports/<profile>/console-output.txt and writes reports/SUMMARY.md. Suites that are EXPECTED to
 * fail (known API defects, intentionally broken locators) are judged against that expectation.
 */
import fs from 'node:fs';
import path from 'node:path';
import { spawnSync } from 'node:child_process';

const ROOT = path.resolve(__dirname, '..');
const REPORTS = path.join(ROOT, 'reports');

interface Suite {
  name: string;
  command: string[];
  reportDir: string;
  expectation: 'pass' | 'fail';
  purpose: string;
}

const SUITES: Suite[] = [
  { name: 'Regression (UI + API)', command: ['npx', 'cucumber-js'], reportDir: 'regression', expectation: 'pass', purpose: 'A2 UI automation + A3 API resilience checks — the CI gate' },
  { name: 'API known issues', command: ['npx', 'cucumber-js', '--profile', 'knownIssues'], reportDir: 'known-issues', expectation: 'fail', purpose: 'A3 validation contract; failures are JSONPlaceholder defects DEF-001…003' },
  { name: 'Self-healing (broken locators)', command: ['npx', 'cucumber-js', '--profile', 'selfHealing'], reportDir: 'self-healing', expectation: 'fail', purpose: 'The 5 intentionally broken locators, left broken' },
  { name: 'Self-healing POC', command: ['npx', 'ts-node', 'self-healing/heal.ts'], reportDir: 'self-healing', expectation: 'pass', purpose: 'Detect → suggest → validate → patch for the 5 broken locators' },
  { name: 'SQL scenarios', command: ['npx', 'ts-node', 'sql/run-queries.ts'], reportDir: '../sql/results', expectation: 'pass', purpose: 'A4 queries, self-checked against designed results' },
];

const stripAnsi = (s: string) => s.replace(/\u001b\[[0-9;]*m/g, '');

interface Counts {
  scenarios: number;
  passed: number;
  failed: number;
}

function cucumberCounts(reportDir: string): Counts | null {
  const file = path.join(REPORTS, reportDir, 'cucumber-report.json');
  if (!fs.existsSync(file)) return null;
  const features = JSON.parse(fs.readFileSync(file, 'utf8')) as Array<{ elements?: Array<{ type: string; steps: Array<{ result: { status: string } }> }> }>;
  const scenarios = features.flatMap((f) => f.elements ?? []).filter((e) => e.type === 'scenario');
  const passed = scenarios.filter((s) => s.steps.every((step) => step.result.status === 'passed')).length;
  return { scenarios: scenarios.length, passed, failed: scenarios.length - passed };
}

function main(): void {
  for (const dir of ['regression', 'known-issues', 'self-healing']) fs.rmSync(path.join(REPORTS, dir), { recursive: true, force: true });

  const rows: string[] = [];
  let unexpected = 0;
  for (const suite of SUITES) {
    console.log(`\n▶ ${suite.name}: ${suite.command.join(' ')}`);
    const started = Date.now();
    const run = spawnSync(suite.command[0], suite.command.slice(1), { cwd: ROOT, encoding: 'utf8', env: { ...process.env, FORCE_COLOR: '0' }, maxBuffer: 64 * 1024 * 1024 });
    const seconds = ((Date.now() - started) / 1000).toFixed(1);
    const output = stripAnsi(`${run.stdout}${run.stderr}`);

    const dir = path.join(REPORTS, suite.reportDir);
    fs.mkdirSync(dir, { recursive: true });
    const logName = suite.name === 'Self-healing POC' ? 'heal-console-output.txt' : 'console-output.txt';
    fs.writeFileSync(path.join(dir, logName), `$ ${suite.command.join(' ')}\n\n${output}`);

    const outcome = run.status === 0 ? 'pass' : 'fail';
    const asExpected = outcome === suite.expectation;
    if (!asExpected) unexpected++;
    const counts = suite.command.includes('cucumber-js') ? cucumberCounts(suite.reportDir) : null;
    const result = counts ? `${counts.passed} passed / ${counts.failed} failed of ${counts.scenarios}` : outcome === 'pass' ? 'all checks passed' : 'failed';
    const html = counts ? `[HTML](${suite.reportDir}/cucumber-report.html) · [log](${suite.reportDir}/console-output.txt)` : `[log](${path.join(suite.reportDir, logName)})`;
    rows.push(`| ${suite.name} | ${suite.purpose} | ${suite.expectation === 'pass' ? 'all pass' : 'fail (by design)'} | ${result} | ${seconds}s | ${asExpected ? '✅ as expected' : '❌ UNEXPECTED'} | ${html} |`);
    console.log(`  ${result} in ${seconds}s — ${asExpected ? 'as expected' : 'UNEXPECTED'}`);
  }

  const summary = [
    '# Test execution summary',
    '',
    `Generated by \`npm run results\` on ${new Date().toISOString()} (Node ${process.version}, ${process.platform}).`,
    '',
    '| Suite | Purpose | Expected | Result | Duration | Verdict | Evidence |',
    '|---|---|---|---|---|---|---|',
    ...rows,
    '',
    'Screenshots for every UI scenario are in `<suite>/screenshots/`; the HTML reports embed them along with',
    'the expected-vs-displayed comparison tables attached by each step. Download an HTML report and open it in a browser.',
    '',
  ].join('\n');
  fs.writeFileSync(path.join(REPORTS, 'SUMMARY.md'), summary);
  console.log(`\n${summary}`);
  if (unexpected) process.exitCode = 1;
}

main();
